static inline u8 *ram(void) { return (u8 *)(uintptr_t)Z32(C4Ram, 0); }
static inline u16 r16(u8 *p, u32 o) { return (u16)(p[o] | p[o + 1] << 8); }
static inline u32 r32(u8 *p, u32 o) { return p[o] | p[o + 1] << 8 | p[o + 2] << 16 | (u32)p[o + 3] << 24; }
static inline void w16(u8 *p, u32 o, u32 v) { p[o] = (u8)v; p[o + 1] = (u8)(v >> 8); }
static inline void w32(u8 *p, u32 o, u32 v) { w16(p, o, v); w16(p, o + 2, v >> 16); }

static void linearray(u8 *r)
{
    u32 line = 0, c4t = 0;
    for (;;) {
        u32 idx = r[0x1F8C];
        if (line) idx = r[0x1F8F];
        if (idx & 0x80) idx |= 0x100;
        int32_t cosv = CosT[idx];
        int32_t num = (int32_t)((u32)(u16)SinT[idx] << 16);
        if (cosv == 0) return;
        c4t = (u32)((int64_t)num / cosv);
        Z32(C4Temp, 0) = c4t;
        int32_t ebx = (int16_t)(uint16_t)(r16(r, 0x1F83) - r16(r, 0x1F89) - 1);
        u32 edx = 0;
        do {
            u8 al;
            if (ebx < 0) {
                al = (u8)(1 - line);
            } else {
                int32_t eax = (int32_t)((u32)c4t * (u32)ebx);
                eax >>= 16;
                int16_t ax = (int16_t)((u16)eax - r16(r, 0x1F80) + r16(r, 0x1F86) + 1 + line);
                if (ax < 0) { ax = 0; if (line) r[0x800 + edx] = 1; }
                if (ax >= 255) ax = 255;
                al = (u8)ax;
            }
            if (!line) r[0x800 + edx] = al; else r[0x900 + edx] = al;
            ebx++; edx++;
        } while (edx != 0xE1);
        if (line) return;
        line = 1;
    }
}

void zl_C4activate(void)
{
    u32 ecx = LG.ecx;
    u8 *r = ram();
    u8 al = (u8)LG.eax;
    if (ecx == 0x1F4F && r[0x1F4D] == 0x0E && !(al & 0xC3)) { al >>= 2; r[0x1F80] = al; LG.eax = (LG.eax & ~0xFFu) | al; return; }
    switch (al) {
    case 0x01: zl_mcall(ZID_WireFrameB); return;
    case 0x00: {
        u32 saved = LG.eax;
        u8 m = r[0x1F4D];
        switch (m) {
        case 0: LG.eax = saved; zl_mcall(ZID_C4ProcessSprites); return;
        case 3: LG.eax = Z32(C4Ram, 0); zl_mcall(ZID_C4SprScaleR); LG.eax = saved; return;
        case 5: LG.eax = Z32(C4Ram, 0); zl_mcall(ZID_C4WireFrame); LG.eax = saved; return;
        case 7: LG.eax = Z32(C4Ram, 0); zl_mcall(ZID_C4SprRotateR); LG.eax = saved; return;
        case 8: LG.eax = saved; zl_mcall(ZID_WireFrameB2); return;
        case 0x0B: LG.eax = Z32(C4Ram, 0); zl_mcall(ZID_C4SprDisintegrate); LG.eax = saved; return;
        case 0x0C: LG.eax = Z32(C4Ram, 0); zl_mcall(ZID_C4BitPlaneWave); LG.eax = saved; return;
        default: return;
        }
    }
    case 0x05: {                                    /* propulsion */
        u16 d3 = r16(r, 0x1F83);
        w16((u8 *)(uintptr_t)ZO_C4values, 2, d3);
        w16((u8 *)(uintptr_t)ZO_C4values, 0, r16(r, 0x1F81));
        int16_t bx = (int16_t)d3;
        int32_t q;
        if (bx == 0 || (q = 0x10000 / bx, q > 32767 || q < -32768)) return;   /* #DE on hardware x86 */
        w16((u8 *)(uintptr_t)ZO_C4values, 6, (u16)q);
        int32_t prod = (int32_t)(int16_t)q * (int16_t)r16(r, 0x1F81);
        u16 dx = (u16)(prod >> 8);
        w16(r, 0x1F80, dx);
        w16((u8 *)(uintptr_t)ZO_C4values, 4, dx);
        return;
    }
    case 0x0D:
        C41FXVal = (short)r16(r, 0x1F80); C41FYVal = (short)r16(r, 0x1F83); C41FDistVal = (short)r16(r, 0x1F86);
        C4Op0D();
        w16(r, 0x1F89, (u16)C41FXVal); w16(r, 0x1F8C, (u16)C41FYVal);
        return;
    case 0x10: {
        u32 e = r16(r, 0x1F80) & 0x1FF;
        int32_t p = (int32_t)(int16_t)CosT[e] * (int16_t)r16(r, 0x1F83);
        w32(r, 0x1F86, (u32)(int32_t)(int16_t)(u16)(((u32)p << 1) >> 16));
        p = (int32_t)(int16_t)SinT[e] * (int16_t)r16(r, 0x1F83);
        int32_t edx = (int16_t)(u16)(((u32)p << 1) >> 16);
        int32_t eax = edx >> 6;
        w32(r, 0x1F89, (u32)(edx - eax));
        return;
    }
    case 0x13: {
        u32 e = r16(r, 0x1F80) & 0x1FF;
        int32_t eax = (int32_t)(int16_t)r16(r, 0x1F83) * 2;
        int32_t p = (int32_t)((u32)(int32_t)CosT[e] * (u32)eax);
        int32_t ebx = (p >> 8) + ((p >> 7) & 1);
        w32(r, 0x1F86, (u32)ebx);
        p = (int32_t)((u32)(int32_t)SinT[e] * (u32)eax);
        ebx = (p >> 8) + ((p >> 7) & 1);
        w16(r, 0x1F89, (u32)ebx);
        r[0x1F8B] = (u8)(ebx >> 16);
        return;
    }
    case 0x15:
        C41FXVal = (short)r16(r, 0x1F80); C41FYVal = (short)r16(r, 0x1F83);
        C4Op15();
        w16(r, 0x1F80, (u16)C41FDist);
        return;
    case 0x1F:
        C41FXVal = (short)r16(r, 0x1F80); C41FYVal = (short)r16(r, 0x1F83);
        C4Op1F();
        w16(r, 0x1F86, (u16)C41FAngleRes);
        return;
    case 0x22: linearray(r); return;
    case 0x25: {
        u32 a = r32(r, 0x1F80) & 0xFFFFFF, b = r32(r, 0x1F83) & 0xFFFFFF;
        w32(r, 0x1F80, a * b);
        return;
    }
    case 0x2D:
        C4WFXVal = (short)r16(r, 0x1F81); C4WFYVal = (short)r16(r, 0x1F84); C4WFZVal = (short)r16(r, 0x1F87);
        *(volatile u8 *)&C4WFScale = r[0x1F90];                         /* byte stores into the low byte of the shorts */
        *(volatile u8 *)&C4WFX2Val = r[0x1F89]; *(volatile u8 *)&C4WFY2Val = r[0x1F8A]; *(volatile u8 *)&C4WFDist = r[0x1F8B];
        C4TransfWireFrame2();
        w16(r, 0x1F80, (u16)C4WFXVal); w16(r, 0x1F83, (u16)C4WFYVal);
        return;
    case 0x40: {
        u16 s = 0;
        for (u32 i = 0; i < 0x800; i++) s += r[i];
        w16(r, 0x1F80, s);
        return;
    }
    case 0x54: {
        int32_t v = (int32_t)(r32(r, 0x1F80) << 8) >> 8;
        int64_t sq = (int64_t)v * v;
        w32(r, 0x1F83, (u32)sq);
        w16(r, 0x1F87, (u32)(sq >> 32));
        return;
    }
    case 0x5C: {
        static const u32 v[12] = { 0xFF000000u, 0xFF00FFFFu, 0xFF000000u, 0x0000FFFFu, 0x0000FFFFu, 0x7FFFFF80u,
                                   0xFF008000u, 0x7FFF007Fu, 0xFFFF7FFFu, 0xFF010000u, 0x0100FEFFu, 0x00FEFF00u };
        for (int i = 0; i < 12; i++) w32(r, i * 4, v[i]);
        return;
    }
    case 0x89: r[0x1F80] = 0x36; r[0x1F81] = 0x43; r[0x1F82] = 0x05; return;
    default: return;
    }
}

void zl_C4ReadReg(void)
{
    LG.eax = (LG.eax & ~0xFFu) | ram()[LG.ecx];
}
void zl_C4WriteReg(void)
{
    u8 *r = ram();
    r[LG.ecx] = (u8)LG.eax;
    if (LG.ecx != 0x1F47) return;
    u32 n = r16(r, 0x1F43);
    if (n == 0) return;                                 /* the asm would loop 2^32 times */
    u8 *src = (u8 *)(uintptr_t)(snesmmap[r[0x1F42]] + r16(r, 0x1F40));
    u8 *dst = r + (r16(r, 0x1F45) & 0x1FFF);
    while (n--) *dst++ = *src++;
}
