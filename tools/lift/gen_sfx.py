#!/usr/bin/env python3
"""Generate core/zl/sfx_tab.h: the SuperFX handler labels (chips/fxemu2*.asm) -> (kind, arg, table, top-level) used by core/zl/sfx.c.
The C interpreter dispatches through the guest tables (FxTable*), whose entries are the code ids of these labels."""
import re, sys, collections, os
SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'upstream', 'zsnes_1_42', 'src', 'chips')

def entries(f):
    ent = []; cur = None
    for ln in open(os.path.join(SRC, f)):
        ln = ln.rstrip('\n')
        m = re.match(r'NEWSYM\s+(\w+)', ln)
        if m: cur = [m.group(1), []]; ent.append(cur); continue
        if cur is None: continue
        s = ln.split(';')[0].rstrip()
        if s.strip(): cur[1].append(' '.join(s.split()))
    return ent

def macro_only(body):
    if len(body) != 1: return None
    m = re.match(r'^([A-Za-z0-9_]+) (.+)$', body[0])
    if not m or m.group(1).lower() in ('ret', 'jmp', 'call'): return None
    return m.group(1), m.group(2)

def ev(a):
    a = re.sub(r'\b0([0-9A-F]+)h\b', r'0x\1', a)
    return eval(a)

kinds = collections.OrderedDict()
labs = []      # (label, kind, arg, tbl, top)
def kind(k):
    kinds.setdefault(k, len(kinds)); return k

PLOT = re.compile(r'^4C128(4|2|8)b(z?)(d?)(l?)$')
def plotarg(sfx, top):
    m = PLOT.match(sfx)
    bits = {'4': 0, '2': 1, '8': 2}[m.group(1)]
    z = 1 if m.group(2) else 0; d = 1 if m.group(3) else 0; low = 1 if m.group(4) else 0
    if top and bits == 2: d = 0            # FxOpd4C1288b*d plot without dithering (the original does)
    return bits | (z << 2) | (d << 3) | (low << 4)

# ---- base (fxemu2.asm) ----
base = {}
for name, body in entries('fxemu2.asm'):
    if not name.startswith('FxOp'): continue
    mo = macro_only(body)
    base[name] = mo if mo else ('FULL', None)
    sfx = name[4:]
    if PLOT.match(sfx): base[name] = ('PLOT', None)

def emit_base(name, tbl, top, lab=None):
    lab = lab or name
    sfx = name[4:]
    ty, arg = base[name]
    if ty == 'PLOT':
        labs.append((lab, kind('PLOT'), plotarg(sfx, top), tbl, top))
    elif ty == 'FULL':
        if name == 'FxOp4C': labs.append((lab, kind('PLOT'), plotarg('4C1284b', top), tbl, top))
        else: labs.append((lab, kind('K_' + name), 0, tbl, top))
    else:
        labs.append((lab, kind('M_' + ty), ev(arg), tbl, top))

for name in base: emit_base(name, 0, 0)

# ---- d family (fxemu2c.asm): the same handlers with a loop-continue tail ----
for name, body in entries('fxemu2c.asm'):
    if not name.startswith('FxOpd'): continue
    b = 'FxOp' + name[5:]
    if name in ('FxOpd00', 'FxOpd4EA1'): labs.append((name, kind('K_' + name), 0, 0, 1)); continue
    if b not in base: raise Exception('no base for ' + name)
    emit_base(b, 0, 1, lab=name)

# ---- b / c families (fxemu2b.asm) ----
for name, body in entries('fxemu2b.asm'):
    m = re.match(r'^FxOp([bc])([0-9A-F]{2})$', name)
    if not m: continue
    fam, op = m.group(1), m.group(2); tbl = 1 if fam == 'b' else 2
    mo = macro_only(body)
    if mo:
        labs.append((name, kind('M_' + mo[0]), ev(mo[1]), tbl, 0))
    else:
        labs.append((name, kind('K_' + name) if int(op, 16) in (0x1E, 0x1F, 0xBF) or op in ('3D', '3E', '3F') else kind('K_BR'), int(op, 16), tbl, 0))

with open(sys.argv[1], 'w') as f:
    f.write('/* generated by tools/lift/gen_sfx.py -- do not edit */\nenum {\n')
    for k in kinds: f.write('    SK_%s,\n' % k)
    f.write('};\nstatic const struct sfxlab { u32 id; u16 kind, arg; u8 tbl, top; } sfx_labs[] = {\n')
    for lab, k, arg, tbl, top in labs: f.write('    { ZID_%s, SK_%s, %d, %d, %d },\n' % (lab, k, arg, tbl, top))
    f.write('};\n')
print('sfx labels:', len(labs), 'kinds:', len(kinds), file=sys.stderr)
