#!/usr/bin/env python3
# Mode 7 + EXTBG test ROM (identity matrix, patterned VRAM/palette): exercises the old engine's drawmode7extbg.
#   mkrom_m7ext.py <out.sfc> [a b c d]   (matrix words, default 0x100 0 0 0x100)
import sys, struct, random
out = sys.argv[1]
mat = [int(x, 0) for x in sys.argv[2:6]] if len(sys.argv) >= 6 else [0x100, 0, 0, 0x100]
rom = bytearray(1 << 20)
c = bytearray()
def e(*b): c.extend(b)
def sta(addr): e(0x8D, addr & 255, addr >> 8)
def lda(v): e(0xA9, v & 255)
e(0x78, 0x18, 0xFB, 0xC2, 0x30, 0xA2, 0xFF, 0x1F, 0x9A, 0xE2, 0x20)
lda(0x8F); sta(0x2100)
lda(0x07); sta(0x2105)
lda(0x40); sta(0x2133)
lda(0x00); sta(0x211A)
for reg, v in zip((0x211B, 0x211C, 0x211D, 0x211E), mat):
    lda(v & 255); sta(reg); lda((v >> 8) & 255); sta(reg)
for reg in (0x211F, 0x2120):
    lda(0x80); sta(reg); lda(0x00); sta(reg)
for reg in (0x210D, 0x210E):
    lda(0); sta(reg); sta(reg)
lda(0x03); sta(0x212C)
lda(0x80); sta(0x2115)
lda(0); sta(0x2116); sta(0x2117)
# loop y = 0..0x3fff:  lo = (y*5)>>2 & 0xff ; hi = y ^ (y>>6) with bit 7 mixed
e(0xC2, 0x10, 0xA0, 0x00, 0x00)               # rep #$10 ; ldy #0
loop = 0x8000 + len(c)
e(0x98)                                         # tya
e(0x0A, 0x0A, 0x18, 0x98)                       # asl asl clc tya (low part: y*4+y)
e(0x65, 0x00) if False else None
sta(0x2118)
e(0x98, 0x4A, 0x4A, 0x4A, 0x4A, 0x4A, 0x4A, 0x45, 0x00 + 0)  # tya lsr x6 eor $00 (dp 0)
sta(0x2119)
e(0xC8, 0xC0, 0x00, 0x40, 0xD0, loop and 0 or 0)  # iny cpy #$4000 bne (offset patched below)
c[-1] = (loop - (0x8000 + len(c))) & 255
lda(0); sta(0x2121)
e(0xA0, 0x00, 0x00)                             # ldy #0
loop2 = 0x8000 + len(c)
e(0x98); sta(0x2122)
e(0x98, 0x49, 0xFF); sta(0x2122)
e(0xC8, 0xC0, 0x00, 0x01, 0xD0, 0)
c[-1] = (loop2 - (0x8000 + len(c))) & 255
e(0xE2, 0x30)
lda(0x0F); sta(0x2100)
lda(0x81); sta(0x4200)
e(0x58)
fin = 0x8000 + len(c)
e(0x4C, fin & 255, fin >> 8)
rom[0:len(c)] = c
rom[0x7F00] = 0x40
hdr = 0x7FC0
rom[hdr:hdr + 21] = b'ZSNES M7EXT TEST     '[:21]
rom[hdr + 0x15] = 0x20; rom[hdr + 0x16] = 0; rom[hdr + 0x17] = 0x0A; rom[hdr + 0x18] = 0; rom[hdr + 0x19] = 0x01; rom[hdr + 0x1A] = 0x33
for a, v in {0x7FE4: 0xFF00, 0x7FE6: 0xFF00, 0x7FE8: 0xFF00, 0x7FEA: 0xFF00, 0x7FEE: 0xFF00, 0x7FF4: 0xFF00, 0x7FF8: 0xFF00, 0x7FFA: 0xFF00, 0x7FFC: 0x8000, 0x7FFE: 0xFF00}.items():
    rom[a:a + 2] = struct.pack('<H', v)
cs = sum(rom) & 0xFFFF
rom[hdr + 0x1C:hdr + 0x20] = struct.pack('<HH', (~cs) & 0xFFFF, cs)
open(out, 'wb').write(rom)
