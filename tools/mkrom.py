#!/usr/bin/env python3
# Generate a random-code SNES test ROM:  mkrom.py <out.sfc> <seed> <chip>   chip: rom|dsp1|sfx|sa1|sdd1
import sys, random, struct
out, seed, chip = sys.argv[1], int(sys.argv[2]), sys.argv[3]
rnd = random.Random(seed)
size = 1 << 20
rom = bytearray(rnd.getrandbits(8) for _ in range(size))
# bias the random code a little towards useful opcodes (loads/stores/ALU/branches) so it does not stop at once
good = [0xA9, 0xA5, 0xAD, 0xAF, 0xB5, 0xBD, 0xB9, 0x85, 0x8D, 0x8F, 0x95, 0x9D, 0x99, 0x69, 0xE9, 0x29, 0x09, 0x49, 0xC9, 0x0A, 0x4A,
        0x1A, 0x3A, 0xE6, 0xC6, 0xAA, 0xA8, 0xE8, 0xC8, 0x18, 0x38, 0xD0, 0xF0, 0x90, 0xB0, 0x80, 0xEA, 0x2A, 0x6A, 0xA2, 0xA0, 0xEB, 0xC2, 0xE2]
for i in range(0x8100, size):
    if rnd.random() < 0.55: rom[i] = rnd.choice(good)
code = bytes([0x78, 0x18, 0xFB, 0xC2, 0x30, 0xA2, 0xFF, 0x1F, 0x9A, 0xE2, 0x20, 0xA9, 0x0F, 0x8D, 0x00, 0x21,
              0xA9, 0x81, 0x8D, 0x00, 0x42, 0x58, 0x4C, 0x20, 0x81])
rom[0x0000:0x0000 + len(code)] = code
# LoROM bank 0 is file offset 0..0x7FFF mapped at $8000; so put reset code at file offset 0
rom[0x100] = 0x40                      # RTI at $8100 for NMI
hdr = 0x7FC0
title = b'ZSNES RANDOM TEST  '.ljust(21)[:21]
rom[hdr:hdr + 21] = title
mapmode, ctype = {'rom': (0x20, 0x00), 'dsp1': (0x20, 0x03), 'sfx': (0x20, 0x13), 'sa1': (0x23, 0x35), 'sdd1': (0x22, 0x43)}[chip]
rom[hdr + 0x15] = mapmode; rom[hdr + 0x16] = ctype; rom[hdr + 0x17] = 0x0A; rom[hdr + 0x18] = 0x03; rom[hdr + 0x19] = 0x01; rom[hdr + 0x1A] = 0x33; rom[hdr + 0x1B] = 0
rom[hdr + 0x1C:hdr + 0x20] = b'\x00\x00\xff\xff'
vec = {0x7FE4: 0x8010, 0x7FE6: 0x8010, 0x7FE8: 0x8010, 0x7FEA: 0x8100, 0x7FEE: 0x8010,
       0x7FF4: 0x8010, 0x7FF8: 0x8010, 0x7FFA: 0x8100, 0x7FFC: 0x8000, 0x7FFE: 0x8010}
for a, v in vec.items(): rom[a:a + 2] = struct.pack('<H', v)
cs = sum(rom) & 0xFFFF
ck = (cs - 0xFF - 0xFF) & 0xFFFF   # approximate; ZSNES only uses the complement pair for detection
rom[hdr + 0x1C:hdr + 0x20] = struct.pack('<HH', (~cs) & 0xFFFF, cs)
open(out, 'wb').write(rom)
