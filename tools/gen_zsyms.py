#!/usr/bin/env python3
# Generate core/zsyms.h: `extern unsigned char NAME[];` for every NEWSYM in the asm sources, so C code can address
# the asm data byte-exactly via the Z8/Z16/Z32/ZP macros.
import re,glob,sys
names=set()
for f in glob.glob('core/**/*.asm',recursive=True)+glob.glob('core/**/*.inc',recursive=True)+glob.glob('core/**/*.mac',recursive=True):
    for l in open(f,errors='replace'):
        m=re.match(r'\s*NEWSYM\s+([A-Za-z_][A-Za-z0-9_]*)',l)
        if m: names.add(m.group(1))
out=['/* generated by tools/gen_zsyms.py -- do not edit */','#ifndef ZSYMS_H','#define ZSYMS_H','#include <stdint.h>',
'typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32; typedef int8_t s8; typedef int16_t s16; typedef int32_t s32;',
'#define Z8(s,o)  (*(volatile u8 *)((u8*)(s)+(o)))','#define Z16(s,o) (*(volatile u16*)((u8*)(s)+(o)))','#define Z32(s,o) (*(volatile u32*)((u8*)(s)+(o)))']
for n in sorted(names):
    if n in ('main','_main'): continue
    out.append('extern u8 %s[];'%n)
out.append('#endif')
open('core/zsyms.h','w').write('\n'.join(out)+'\n')
print(len(names),'symbols')
