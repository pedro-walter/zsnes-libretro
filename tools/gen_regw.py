# Generates core/cpu/regw_ids.inc (nasm) and core/cpu/regw_ids.h from one handler list.
import sys
ids = []
def add(n, label): ids.append((n, label))
for r in range(0x2100, 0x2134): add("R%04X" % r, ("regINVALIDw" if r in (0x2118, 0x2119) else "reg%04Xw" % r))
for r in range(0x2140, 0x2144): add("R%04X" % r, "reg%04Xw" % r)
for r in range(0x2180, 0x2184): add("R%04X" % r, "reg%04Xw" % r)
for r in (0x4016, 0x4017, *range(0x4200, 0x420B), 0x420D, 0x420E, 0x4210, 0x4211, 0x4212, 0x4216):
    add("R%04X" % r, "reg%04Xw" % r)
for k in "0123456789A": add("R43X%s" % k, "reg43%s%sw" % ("X" if k in "01A" else "x", k))
for v in ("2118", "2118inc", "2118inc8", "2118inc8inc", "2119", "2119inc", "2119inc8", "2119inc8inc"):
    add("V" + v, "reg" + v)
out = "core/cpu/"
with open(out + "regw_ids.h", "w") as h:
    h.write("/* generated by tools/gen_regw.py */\nenum {\n")
    for i, (n, _) in enumerate(ids): h.write("    RW_%s = %d,\n" % (n, i))
    h.write("    RW_COUNT = %d\n};\n" % len(ids))
with open(out + "regw_ids.inc", "w") as a:
    a.write("; generated by tools/gen_regw.py\n%define RW_COUNT " + str(len(ids)) + "\n")
    a.write("%macro RW_LABELS 0\n")
    for _, l in ids: a.write("    dd %s\n" % l)
    a.write("%endmacro\n")

# ---- read handlers ----
rids = []
def radd(n, label): rids.append((n, label))
radd("R2100", "reg2100r")
for r in range(0x2134, 0x2140): radd("R%04X" % r, "reg%04Xr" % r)
for r in range(0x2140, 0x2144): radd("R%04X" % r, "reg%04Xr" % r)
radd("R2144", "reg2144r"); radd("R2180", "reg2180r")
radd("R4016", "reg4016r"); radd("R4017", "reg4017r"); radd("R4100", "reg4100r"); radd("RZERO", "reg420Ar")
for r in range(0x4210, 0x4220): radd("R%04X" % r, "reg%04Xr" % r)
radd("R43XX", "reg43XXr"); radd("RINVALID", "regINVALID")
with open(out + "regr_ids.h", "w") as h:
    h.write("/* generated by tools/gen_regw.py */\nenum {\n")
    for i, (n, _) in enumerate(rids): h.write("    RR_%s = %d,\n" % (n, i))
    h.write("    RR_COUNT = %d\n};\n" % len(rids))
with open(out + "regr_ids.inc", "w") as a:
    a.write("; generated by tools/gen_regw.py\n%define RR_COUNT " + str(len(rids)) + "\n")
    a.write("%macro RR_LABELS 0\n")
    for _, l in rids: a.write("    dd %s\n" % l)
    a.write("%endmacro\n")
